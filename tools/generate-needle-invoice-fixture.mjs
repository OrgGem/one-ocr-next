const lines=['INVOICE','SUPPLIER: ACME TOOLS LTD.','INVOICE NUMBER: INV-042','TOTAL: 1250.00 USD'];
const width=2000,height=560,scale=11,channels=3,pixels=Buffer.alloc(width*height*channels,255);
function setBlack(x,y) {
  const offset=(y*width+x)*channels;
  pixels[offset]=0;pixels[offset+1]=0;pixels[offset+2]=0;
}
for(let lineIndex=0;lineIndex<lines.length;lineIndex++) {
  const line=lines[lineIndex],lineWidth=(line.length*6-1)*scale,startX=Math.floor((width-lineWidth)/2),startY=42+lineIndex*120;
  if(lineWidth>width-80)throw new Error(`Fixture line does not fit: ${line}`);
  for(let character=0;character<line.length;character++) {
    const pattern=glyphs[line[character]];
    if(!pattern)throw new Error(`Missing bitmap glyph: ${line[character]}`);
    for(let row=0;row<7;row++)for(let column=0;column<5;column++)if(pattern[row][column]==='1') {
      for(let dy=0;dy<scale;dy++)for(let dx=0;dx<scale;dx++)setBlack(startX+(character*6+column)*scale+dx,startY+row*scale+dy);
    }
  }
}

const png=await sharp(pixels,{raw:{width,height,channels}}).png({compressionLevel:9,adaptiveFiltering:false}).toBuffer();
